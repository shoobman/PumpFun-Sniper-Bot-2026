export function hasTraderWallets(
	holders: readonly IHolder[],
	avoidBlacklisted?: boolean,
): number {
	let holdersNum = 0

	for (let i = 0; i < holders.length; i++) {
		const meta = traderWallets.get(holders[i].owner)
		if (!meta) continue

		if (avoidBlacklisted === undefined || meta.blacklisted) {
			holdersNum += 1
		}
	}
	return holdersNum
}

export function getTraderNames(holders: readonly IHolder[]): IWallet[] {
	const matchedNames: IWallet[] = []

	for (let i = 0; i < holders.length; i++) {
		const wallet = traderWallets.get(holders[i].owner)
		if (!wallet) continue
		matchedNames.push({ wallet: holders[i].owner, name: wallet.name })
	}
	return matchedNames
}
